// Writes src/data/nodisenchant.js: the items WoW: Forever's game files mark as "can't be disenchanted".
//
//   node tools/no-disenchant.js
//
// The mark is flag 0x8000 in ItemSparse's Flags_0 (wago.tools publishes the table per game build).
// Without it, quality + armor/weapon + item level would say e.g. Greater Magic Wand can be disenchanted,
// but the game refuses it ("not a valid item", checked in game 2026-11-22). Only green, blue and purple
// equippable items are kept, the ones the disenchanting rules would otherwise accept.
// Run it again when a new game build changes items; the file records which build it came from.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseCsv } from "../pipeline/recipeinfo.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const WAGO = "https://wago.tools";
const UA = { "User-Agent": "ForeverAnvil-price-job" };
const NO_DISENCHANT = 0x8000;

/** ItemSparse rows → sorted ids of flagged green/blue/purple equippable items */
export function noDisenchantIds(rows) {
  const ids = [];
  for (const r of rows) {
    const q = Number(r.OverallQualityID);
    if ((Number(r.Flags_0) & NO_DISENCHANT) && q >= 2 && q <= 4 && Number(r.InventoryType) > 0) ids.push(Number(r.ID));
  }
  return ids.sort((a, b) => a - b);
}

async function main() {
  const builds = await (await fetch(WAGO + "/api/builds", { headers: UA })).json();
  const build = ((builds.wowf || [])[0] || {}).version;
  if (!build) throw new Error("wago.tools lists no WoW: Forever build");
  const res = await fetch(`${WAGO}/db2/ItemSparse/csv?build=${build}`, { headers: UA });
  if (!res.ok) throw new Error(`ItemSparse: HTTP ${res.status}`);
  const ids = noDisenchantIds(parseCsv(await res.text()));
  const lines = [];
  for (let i = 0; i < ids.length; i += 16) lines.push("  " + ids.slice(i, i + 16).join(", ") + ",");
  const text = [
    "// Generated by tools/no-disenchant.js from WoW: Forever's game files (ItemSparse, Flags_0 & 0x8000). Do not edit.",
    "// Green, blue and purple equippable items the game won't let you disenchant (e.g. Greater Magic Wand).",
    `export const NO_DISENCHANT_BUILD = ${JSON.stringify(build)};`,
    "export const NO_DISENCHANT = new Set([",
    ...lines,
    "]);",
    ""
  ].join("\n");
  fs.writeFileSync(path.join(ROOT, "src/data/nodisenchant.js"), text);
  console.log(`${ids.length} items from build ${build} → src/data/nodisenchant.js`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((e) => { console.error(e.message); process.exitCode = 1; });
}
